// Builds src/lib/digit-templates.ts from the glyphs that
// scripts/digit-templates/render_fonts.py rendered (see that file for how to
// run both). Each glyph is shrunk with normalizeGlyph, the same function the
// photo reader uses on a photographed digit, so the two compare like for like.
import { readFileSync, writeFileSync } from "node:fs";
import { normalizeGlyph } from "../src/lib/photo";

type Glyph = { font: string; digit: number; width: number; height: number; bits: string };

const glyphs: Glyph[] = JSON.parse(readFileSync(process.argv[2]!, "utf8"));
const lines = glyphs.map((g) => {
  const bits = Array.from(g.bits, (ch) => (ch === "1" ? 1 : 0));
  const pixels = Array.from(normalizeGlyph(bits, g.width, g.height), (v) => Math.round(v * 15).toString(16)).join("");
  const aspect = Math.round((g.width / g.height) * 1000) / 1000;
  return `  { digit: ${g.digit}, aspect: ${aspect}, pixels: "${pixels}" }, // ${g.font}`;
});

const source = `// Generated by scripts/build-digit-templates.ts. Do not edit by hand.
//
// The digits 1 to 9 in common printed fonts, each shrunk to TEMPLATE_SIZE by
// TEMPLATE_SIZE pixels. Each character of \`pixels\` is one pixel, row by row,
// in hex: 0 is paper, f is fully inked. \`aspect\` is the glyph's width over its
// height before shrinking. src/lib/photo.ts compares a photographed digit
// with every entry and takes the closest.
import type { Digit } from "./sudoku";

export const TEMPLATE_SIZE = 16;

export const DIGIT_TEMPLATES: readonly { digit: Digit; aspect: number; pixels: string }[] = [
${lines.join("\n")}
];
`;
writeFileSync(new URL("../src/lib/digit-templates.ts", import.meta.url), source);
console.log(`Wrote ${lines.length} templates.`);
